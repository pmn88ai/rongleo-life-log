function build() {
  const seenIds = new Map();
  const list = [];
  for (const category of Object.keys(RAW)) {
    for (const entry of RAW[category]) {
      let id = `${category}_${slugify(entry.name)}`;
      if (seenIds.has(id)) {
        const n = seenIds.get(id) + 1;
        seenIds.set(id, n);
        id = `${id}_${n}`;
      } else {
        seenIds.set(id, 1);
      }
      list.push({
        id,
        name: entry.name,
        emoji: entry.emoji,
        category,
        type: entry.type,
        unit: entry.unit,
        defaultValue: entry.defaultValue,
        aliases: entry.aliases,
        active: true,
        favorite: false,
      });
    }
  }
  return list;
}

export const EVENT_LIBRARY = build();

export function getLibraryEntry(id) {
  return EVENT_LIBRARY.find(e => e.id === id) || null;
}
